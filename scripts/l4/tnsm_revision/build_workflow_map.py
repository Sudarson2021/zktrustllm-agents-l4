#!/usr/bin/env python3
"""Generate an editable functional map and full node inventory from frozen JSON."""
from pathlib import Path
import xml.etree.ElementTree as ET
import hashlib,json
ROOT=Path(__file__).resolve().parents[3]
PAPER=ROOT/'paper/tnsm_revision_20261015'
SOURCE=ROOT/'docs/l4/supervisor_258/evidence/final_paper_n8n_20260718/workflows/L4FinalPaperDemoV1.verified.json'

def main():
    raw=SOURCE.read_bytes();o=json.loads(raw);o=o[0] if isinstance(o,list) else o
    executable=[n for n in o['nodes'] if n['type']!='n8n-nodes-base.stickyNote']
    sticky=[n for n in o['nodes'] if n['type']=='n8n-nodes-base.stickyNote']
    groups=[('Input and retrieval',range(0,7)),('Parallel assessment',range(7,19)),
            ('Consensus and roles',range(19,25)),('Policy and audit',range(25,29)),
            ('Knowledge base',range(29,36)),('Governed outcomes',list(range(36,44))+[52])]
    # Order is the frozen export order. Refuse a different export rather than
    # silently publishing a misleading grouping.
    if len(o['nodes'])!=54 or len(executable)!=45:raise ValueError('unexpected export node inventory')
    inventory=[]
    for title,indices in groups:
        inventory.append({'group':title,'nodes':[o['nodes'][i]['name'] for i in indices]})
    assigned=[n for g in inventory for n in g['nodes']]
    if set(assigned)!={n['name'] for n in executable}:raise ValueError('functional map omits an executable node')
    report={'schema':'zktrustllm.tnsm.workflow_map.v1','source_sha256':hashlib.sha256(raw).hexdigest(),
            'total_nodes':54,'computational_nodes':45,'documentation_nodes':9,'groups':inventory,
            'edge_count':sum(len(edges) for c in o['connections'].values() for output in c.values() for edges in output),
            'scope':'Functional grouping generated from archived JSON, not a new execution trace or exact edge-layout rendering.'}
    out=PAPER/'evidence/derived';out.mkdir(parents=True,exist_ok=True)
    (out/'workflow_node_inventory.json').write_text(json.dumps(report,indent=2,ensure_ascii=False)+'\n')
    content=r'''% Generated by build_workflow_map.py from the archived 54-node export.
\begin{tikzpicture}[
 font=\sffamily\footnotesize,
 box/.style={draw=trustblue,rounded corners=2pt,fill=blue!3,align=center,
 text width=4.65cm,minimum height=1.55cm,inner sep=6pt},
 flow/.style={-Latex,thick}]
'''
    # The arrows below express the functional sequence; exact graph edges are
    # independently available in the export and inventory, not inferred here.
    for i,g in enumerate(inventory):
        x=[0,5.5,11][i%3];y=0 if i<3 else -2.35
        title=g['group'];count=len(g['nodes'])
        content+=rf'\node[box] (g{i}) at ({x},{y}) {{\textbf{{{title}}}\\{count} computational nodes}};'+'\n'
    content+=r'''
\draw[flow] (g0)--(g1);\draw[flow] (g1)--(g2);
\draw[flow] (g2.south)--++(0,-.45)-|(g3.north);
\draw[flow] (g3.south)--++(0,-.4)-|(g5.south);
\draw[flow,dashed] (g4.north)--(g1.south);
\end{tikzpicture}
'''
    (PAPER/'figures/workflow_map.tex').write_text(content)
    # Complete editable edge-level diagram. Node positions come from the export;
    # display labels are node names, not a screenshot or a generated illustration.
    mx=ET.Element('mxfile',host='app.diagrams.net');diagram=ET.SubElement(mx,'diagram',name='Archived n8n topology')
    model=ET.SubElement(diagram,'mxGraphModel',grid='1',page='0');cells=ET.SubElement(model,'root')
    ET.SubElement(cells,'mxCell',id='0');ET.SubElement(cells,'mxCell',id='1',parent='0')
    ids={n['name']:n['id'] for n in o['nodes']}
    for n in o['nodes']:
        style='rounded=1;whiteSpace=wrap;html=0;fillColor=#e8f0fb;'
        if n['type']=='n8n-nodes-base.stickyNote':style+='fillColor=#fff2cc;'
        cell=ET.SubElement(cells,'mxCell',id=n['id'],value=n['name'],style=style,vertex='1',parent='1')
        geo=ET.SubElement(cell,'mxGeometry',x=str(n['position'][0]),y=str(n['position'][1]),width='240',height='80')
        geo.set('as','geometry')
    edge=0
    for name,connections in o['connections'].items():
        for kind,ports in connections.items():
            for port,targets in enumerate(ports):
                for target in targets:
                    edge+=1;cell=ET.SubElement(cells,'mxCell',id=f'edge-{edge}',value=f'{kind}:{port}',source=ids[name],target=ids[target['node']],edge='1',parent='1',style='edgeStyle=orthogonalEdgeStyle;endArrow=block;html=0;')
                    geo=ET.SubElement(cell,'mxGeometry',relative='1');geo.set('as','geometry')
    ET.ElementTree(mx).write(PAPER/'figures/workflow_topology.drawio',encoding='utf-8',xml_declaration=True)
    print(json.dumps({k:report[k] for k in ['total_nodes','computational_nodes','documentation_nodes','edge_count']}))
if __name__=='__main__':main()
