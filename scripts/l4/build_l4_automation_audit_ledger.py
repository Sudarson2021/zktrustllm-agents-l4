def write_pdf(ledger):
    try:
        from reportlab.lib import colors
        from reportlab.lib.pagesizes import A4
        from reportlab.lib.styles import getSampleStyleSheet, ParagraphStyle
        from reportlab.lib.units import inch
        from reportlab.platypus import SimpleDocTemplate, Paragraph, Spacer, Table, TableStyle
    except Exception as exc:
        print(f"PDF generation skipped because reportlab is unavailable: {exc}")
        return

    styles = getSampleStyleSheet()
    title = ParagraphStyle(
        "TitleCenter",
        parent=styles["Title"],
        alignment=1,
        fontSize=16,
        leading=20,
        spaceAfter=12,
    )

    body = ParagraphStyle(
        "Body",
        parent=styles["BodyText"],
        fontSize=9,
        leading=12,
        spaceAfter=8,
    )

    doc = SimpleDocTemplate(
        str(LEDGER_PDF),
        pagesize=A4,
        rightMargin=0.55 * inch,
        leftMargin=0.55 * inch,
        topMargin=0.55 * inch,
        bottomMargin=0.55 * inch,
    )

    story = [
        Paragraph("Step 101 Hash-Chained Automation Audit Ledger", title),
        Paragraph("ZKTrustLLM-Agents Level 4", styles["Heading2"]),
        Paragraph(
            "This PDF records the hash-chained audit ledger for the closed-loop automation workflow covering Steps 96-100.",
            body,
        ),
        Paragraph(f"Created at: {ledger['createdAt']}", body),
        Paragraph(f"Final ledger hash: {ledger['finalLedgerHash']}", body),
        Spacer(1, 10),
    ]

    table_data = [["#", "Step", "Component", "Exists", "Status", "SHA-256 short", "Entry hash short"]]

    for entry in ledger["entries"]:
        table_data.append(
            [
                entry["index"],
                entry["step"],
                entry["component"],
                str(entry["exists"]),
                entry["statusOrDecision"],
                entry["sha256"][:12] if entry["sha256"] else "MISSING",
                entry["entryHash"][:12],
            ]
        )

    table = Table(table_data, repeatRows=1, colWidths=[0.3 * inch, 0.75 * inch, 1.7 * inch, 0.45 * inch, 1.05 * inch, 0.9 * inch, 0.9 * inch])
    table.setStyle(
        TableStyle(
            [
                ("BACKGROUND", (0, 0), (-1, 0), colors.lightgrey),
                ("GRID", (0, 0), (-1, -1), 0.25, colors.grey),
                ("FONTNAME", (0, 0), (-1, 0), "Helvetica-Bold"),
                ("FONTSIZE", (0, 0), (-1, -1), 7),
                ("VALIGN", (0, 0), (-1, -1), "TOP"),
            ]
        )
    )

    story.append(table)
    story.append(Spacer(1, 10))
    story.append(
        Paragraph(
            "Governance boundary: this ledger is read-only. It records evidence and does not push code, deploy systems, submit papers, delete evidence, or run privileged commands.",
            body,
        )
    )

    doc.build(story)


