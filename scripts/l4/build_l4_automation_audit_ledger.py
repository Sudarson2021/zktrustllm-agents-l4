def rel(path: Path) -> str:
    try:
        return str(path.relative_to(ROOT))
    except ValueError:
        return str(path)


def sha256_file(path: Path) -> str:
    h = hashlib.sha256()
    with path.open("rb") as f:
        for block in iter(lambda: f.read(1024 * 1024), b""):
            h.update(block)
    return h.hexdigest()


def sha256_json(obj) -> str:
    payload = json.dumps(obj, sort_keys=True, separators=(",", ":")).encode("utf-8")
    return hashlib.sha256(payload).hexdigest()


def read_json_if_possible(path: Path):
    if not path.exists() or path.suffix.lower() != ".json":
        return None
    try:
        return json.loads(path.read_text())
    except Exception:
        return None


def extract_status(path: Path):
    data = read_json_if_possible(path)
    if not isinstance(data, dict):
        return "N/A"

    if "overallStatus" in data:
        return str(data["overallStatus"])

    if "status" in data:
        return str(data["status"])

    if "decision" in data and isinstance(data["decision"], dict):
        return str(data["decision"].get("primaryAction", "DECISION_PRESENT"))

    if "primaryAction" in data:
        return str(data["primaryAction"])

    return "JSON_PRESENT"


def build_ledger():
    created_at = datetime.now(timezone.utc).isoformat()
    previous_hash = "GENESIS"
    entries = []

    for index, item in enumerate(ARTIFACTS, start=1):
        artifact_path = ROOT / item["path"]
        exists = artifact_path.exists()

        entry = {
            "index": index,
            "createdAt": created_at,
            "step": item["step"],
            "component": item["component"],
            "path": item["path"],
            "exists": exists,
            "sizeBytes": artifact_path.stat().st_size if exists else 0,
            "sha256": sha256_file(artifact_path) if exists else None,
            "statusOrDecision": extract_status(artifact_path) if exists else "MISSING",
            "meaning": item["meaning"],
            "previousEntryHash": previous_hash,
        }

        entry["entryHash"] = sha256_json(entry)
        previous_hash = entry["entryHash"]
        entries.append(entry)

    ledger = {
        "experiment": "step101_hash_chained_automation_audit_ledger",
        "createdAt": created_at,
        "purpose": "Create a tamper-evident hash-chained audit ledger for the L4 closed-loop automation pipeline.",
        "coverage": "Steps 96-100 plus supervisor-facing report artifacts.",
        "entryCount": len(entries),
        "missingArtifacts": [e["path"] for e in entries if not e["exists"]],
        "genesisHash": "GENESIS",
        "finalLedgerHash": previous_hash,
        "entries": entries,
        "files": {
            "ledgerJson": rel(LEDGER_JSON),
            "ledgerJsonl": rel(LEDGER_JSONL),
            "ledgerCsv": rel(LEDGER_CSV),
            "ledgerMarkdown": rel(LEDGER_MD),
            "ledgerPdf": rel(LEDGER_PDF),
        },
    }

    return ledger


def write_json_outputs(ledger):
    LEDGER_JSON.write_text(json.dumps(ledger, indent=2))

    with LEDGER_JSONL.open("w") as f:
        for entry in ledger["entries"]:
            f.write(json.dumps(entry, sort_keys=True) + "\n")

    with LEDGER_CSV.open("w", newline="") as f:
        writer = csv.DictWriter(
            f,
            fieldnames=[
                "index",
                "step",
                "component",
                "path",
                "exists",
                "sizeBytes",
                "sha256",
                "statusOrDecision",
                "previousEntryHash",
                "entryHash",
            ],
        )
        writer.writeheader()
        for entry in ledger["entries"]:
            writer.writerow({k: entry.get(k) for k in writer.fieldnames})

